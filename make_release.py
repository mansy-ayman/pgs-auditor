def patch_credentials(text):
    """Makes the .pyw read the built-in key first (credentials.json next to the exe is only a fallback)."""
    eol = eol_of(text)
    loader = eol.join([
        CRED_START,
        "def load_credentials_info():",
        '    """The Google key built into the program (pgs_credentials.py). Falls back to a credentials.json next to it."""',
        "    try:",
        "        from pgs_credentials import CREDENTIALS_JSON",
        "        return json.loads(CREDENTIALS_JSON)",
        "    except Exception:",
        "        pass",
        "    try:",
        '        with open(CREDENTIALS_FILE, "r", encoding="utf-8") as f:',
        "            return json.load(f)",
        "    except Exception:",
        "        return None",
        CRED_END,
    ]) + eol

    pat = re.compile(re.escape(CRED_START) + r".*?" + re.escape(CRED_END) + r"(\r?\n)?", re.S)
    if pat.search(text):
        text = pat.sub(lambda m: loader, text, count=1)
    else:
        m = re.search(r"^CREDENTIALS_FILE\s*=[^\n]*\n", text, re.M)
        if not m:
            raise RuntimeError("could not find the line  CREDENTIALS_FILE = ...  in the .pyw")
        text = text[:m.end()] + eol + loader + text[m.end():]

    old = "creds = Credentials.from_service_account_file(CREDENTIALS_FILE, scopes=scopes)"
    new = eol.join([
        "info = load_credentials_info()",
        "    if info is None:",
        '        raise FileNotFoundError("Google credentials are missing (not built into the program and no credentials.json found)")',
        "    creds = Credentials.from_service_account_info(info, scopes=scopes)",
    ])
    if old in text:
        text = text.replace(old, new, 1)
    elif "from_service_account_info(info, scopes=scopes)" not in text:
        raise RuntimeError("could not find the Credentials.from_service_account_file(...) line in get_gspread_client")

    old = "if not os.path.exists(CREDENTIALS_FILE):"
    if old in text:
        text = text.replace(old, "if load_credentials_info() is None:", 1)
    elif "if load_credentials_info() is None:" not in text:
        raise RuntimeError("could not find the  if not os.path.exists(CREDENTIALS_FILE):  check in the .pyw")
    return text


def patch_spec(text, ico_name):
    eol = eol_of(text)
    hm = re.search(r"hiddenimports\s*=\s*\[([^\]]*)\]", text)           # make sure PyInstaller bundles our generated modules
    if hm:
        have = re.findall(r"""['"]([^'"]+)['"]""", hm.group(1))
        want = have + [n for n in ("updater", "pgs_icon", "pgs_store", "pgs_key", "tzdata") if n not in have]
        text = text[:hm.start()] + "hiddenimports=[" + ", ".join(repr(n) for n in want) + "]" + text[hm.end():]
    exe_at = text.find("EXE(")
    if exe_at < 0:
        raise RuntimeError("could not find EXE( in the .spec file")
    icon_line = f"icon=['{ico_name}'],"
    m = re.compile(r"^(\s*)icon\s*=\s*[^\n]*?,\s*$", re.M).search(text, exe_at)
    if m:
        return text[:m.start()] + m.group(1) + icon_line + text[m.end():]
    m = re.compile(r"^(\s*)name\s*=\s*[^\n]*,[ \t]*\r?$", re.M).search(text, exe_at)
    if not m:
        raise RuntimeError("could not find  name='PGS_Tool',  inside EXE( in the .spec file")
    return text[:m.end()] + eol + m.group(1) + icon_line + text[m.end():]


