# make_release.py  -  run this on YOUR PC every time you want to publish a new version.
# Keep it in the same folder as the .pyw, PGS_Tool.spec, updater.py, credentials.json and the logo.
#
# What it does, in order:
#   1) checks everything is in place
#   2) turns the logo into the exe icon (PGS_Tool.ico) + a small icon for the tool window (pgs_icon.py)
#   3) raises APP_VERSION in the .pyw by one (1.0.0 -> 1.0.1), injects the icon code, adds icon= to the .spec
#   4) builds PGS_Tool.exe with PyInstaller   (if the build fails, your files are put back as they were)
#   5) updates the extension: same version number as the tool, icons from the PGS SINTENAL icon,
#      self-reload code added to background.js, then zips it
#   6) writes version.json and fills a folder on your Desktop with everything ready to copy
#
# Also automatic: your credentials.json is built into the exe (pgs_credentials.py), the updater is wired into
# the .pyw, and the Drive folder ID is written into the .pyw from DRIVE_FOLDER below.
#
# ONE version number for both: every run takes the higher of (APP_VERSION, extension version), adds one,
# and writes it to BOTH the .pyw and the extension's manifest.json.
#
# Needs once:   pip install pyinstaller pillow
# Run:          python make_release.py            (add  --no-build  to test everything except the exe build)
