def square_logo(png_path):
    """Opens a logo, flattens it on white, trims the empty border (if CROP_LOGO) and makes it square."""
    from PIL import Image
    img = Image.open(png_path).convert("RGBA")
    bg = Image.new("RGBA", img.size, (255, 255, 255, 255))
    img = Image.alpha_composite(bg, img).convert("RGB")

    if CROP_LOGO:                                                   # cut away the near-white border / soft shadow
        mask = img.convert("L").point(lambda v: 255 if v < 225 else 0)
        box = mask.getbbox()
        if box:
            pad = int(max(box[2] - box[0], box[3] - box[1]) * 0.06)
            box = (max(0, box[0] - pad), max(0, box[1] - pad), min(img.width, box[2] + pad), min(img.height, box[3] + pad))
            img = img.crop(box)

    side = max(img.size)
    square = Image.new("RGB", (side, side), (255, 255, 255))
    square.paste(img, ((side - img.width) // 2, (side - img.height) // 2))
    return square


