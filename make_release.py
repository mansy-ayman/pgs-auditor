def drive_session(key_info):
    """Full Drive access (needs Editor rights on the update folder), using the key written into the .pyw."""
    from google.oauth2.service_account import Credentials
    from google.auth.transport.requests import AuthorizedSession
    creds = Credentials.from_service_account_info(key_info, scopes=["https://www.googleapis.com/auth/drive"])
    return AuthorizedSession(creds)


def drive_find(sess, folder_id, name):
    r = sess.get("https://www.googleapis.com/drive/v3/files", params={
        "q": f"'{folder_id}' in parents and name = '{name}' and trashed = false",
        "fields": "files(id,name,modifiedTime)", "pageSize": 100,
        "supportsAllDrives": "true", "includeItemsFromAllDrives": "true"}, timeout=60)
    if r.status_code >= 400:
        raise RuntimeError(f"{r.status_code} {r.text[:300]}")
    data = r.json()
    if "id" not in data:
        raise RuntimeError(f"Google reply had no id: {str(data)[:300]}")
    return data["id"]


def drive_upload(sess, folder_id, path):
    boundary = "pgs_release_boundary_7f3a"
    meta = json.dumps({"name": path.name, "parents": [folder_id]})
    body = (f"--{boundary}\r\nContent-Type: application/json; charset=UTF-8\r\n\r\n{meta}\r\n"
            f"--{boundary}\r\nContent-Type: application/octet-stream\r\n\r\n").encode("utf-8")
    body += path.read_bytes()
    body += f"\r\n--{boundary}--\r\n".encode("utf-8")
    r = sess.post("https://www.googleapis.com/upload/drive/v3/files",
                  params={"uploadType": "multipart", "supportsAllDrives": "true", "fields": "id,name"},
                  headers={"Content-Type": f"multipart/related; boundary={boundary}"},
                  data=body, timeout=900)
    r.raise_for_status()
    return r.json()["id"]


def drive_trash(sess, file_id):
    """Moves a file to the Drive trash (restorable for 30 days). It is NOT deleted forever."""
    r = sess.patch(f"https://www.googleapis.com/drive/v3/files/{file_id}",
                   params={"supportsAllDrives": "true"}, json={"trashed": True}, timeout=60)
    r.raise_for_status()


def publish_to_drive(folder_id, files_in_order, key_info):
    """For each release file: upload the NEW one first, then trash the OLD one with the same name.
    version.json is last, so no PC sees the new version number before the new files exist."""
    sess = drive_session(key_info)
    for path in files_in_order:
        old_ids = [f["id"] for f in drive_find(sess, folder_id, path.name)]
        drive_upload(sess, folder_id, path)
        for old_id in old_ids:
            drive_trash(sess, old_id)
        say(f"      uploaded {path.name} (old copies moved to trash: {len(old_ids)})")


def push_to_github(new_v):
    """Commits and pushes the project to GitHub. .gitignore keeps credentials and generated files out."""
    def git(*args):
        return subprocess.run(["git", *args], cwd=str(HERE), capture_output=True, text=True)
    if git("rev-parse", "--is-inside-work-tree").returncode != 0:
        return "not a git repository - GitHub was NOT updated"
    git("add", "-A")
    if git("diff", "--cached", "--quiet").returncode == 0:
        return "no file changes - nothing new to push to GitHub"
    c = git("commit", "-m", f"Release {new_v}")
    if c.returncode != 0:
        return "commit failed: " + (c.stderr or c.stdout).strip()[-300:]
    p = git("push")
    if p.returncode != 0:
        return "push failed: " + (p.stderr or p.stdout).strip()[-300:]
    return f"pushed release {new_v} to GitHub"


