def make_credentials_module(cred_path):
    """pgs_credentials.py = the content of credentials.json as text, so it travels inside the exe."""
    info = json.loads(read_text(cred_path).lstrip("\ufeff"))
    if not info.get("private_key") or not info.get("client_email"):
        raise ValueError("it has no private_key / client_email")
    compact = json.dumps(info, separators=(",", ":"), ensure_ascii=False)
    write_text(HERE / "pgs_credentials.py",
               "# AUTO-GENERATED by make_release.py from credentials.json - do not edit by hand\n"
               f"CREDENTIALS_JSON = {compact!r}\n")


