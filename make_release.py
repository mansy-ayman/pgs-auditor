def inject_icon_code(text):
    eol = eol_of(text)
    block = eol.join([
        ICON_START,
        "try:",
        "    from pgs_icon import ICON_PNG_B64",
        "    root._pgs_icon = tk.PhotoImage(data=ICON_PNG_B64)",
        "    root.iconphoto(True, root._pgs_icon)",
        "except Exception:",
        "    pass",
        ICON_END,
    ]) + eol
    pat = re.compile(re.escape(ICON_START) + r".*?" + re.escape(ICON_END) + r"(\r?\n)?", re.S)
    if pat.search(text):
        return pat.sub(lambda m: block, text, count=1)               # already there: refresh it
    m = re.search(r"^root\.mainloop\(\)", text, re.M)
    if not m:
        raise RuntimeError("could not find the line  root.mainloop()  in the .pyw")
    return text[:m.start()] + block + eol + text[m.start():]


