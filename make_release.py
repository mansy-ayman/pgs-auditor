def inject_block(text, start, end, lines):
    """Adds (or refreshes) a marked block right above  root.mainloop()  in the .pyw."""
    eol = eol_of(text)
    block = eol.join([start] + lines + [end]) + eol
    pat = re.compile(re.escape(start) + r".*?" + re.escape(end) + r"(\r?\n)?", re.S)
    if pat.search(text):
        return pat.sub(lambda m: block, text, count=1)
    m = re.search(r"^root\.mainloop\(\)", text, re.M)
    if not m:
        raise RuntimeError("could not find the line  root.mainloop()  in the .pyw")
    return text[:m.start()] + block + eol + text[m.start():]


